const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
(async()=>{
const source=fs.readFileSync(path.resolve(__dirname,'../../HawalaExchange.Web/wwwroot/js/selection-amounts.js'),'utf8');
const {summarize,money,decimalUnits}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const row=(id,currency,original,converted=null,settlementCurrency='USD',cancelled=false,correspondentId=1)=>({id,currency,original,converted,settlementCurrency,cancelled,correspondentId,correspondent:'Agent '+correspondentId});
const cache=new Map([row(1,'AFN','100000','1538.46153846'),row(2,'PKR','60000','263.15789474'),row(3,'USD','1000','1000'),row(4,'AFN','140','2','USD',true),row(5,'AFN','5000',null,'AFN',false,2)].map(x=>[x.id,x]));
const result=summarize(new Set([1,2,3,4,5]),cache);
assert.equal(money(result.grand.find(x=>x.currency==='USD').amount),'2,802');
assert.equal(money(result.grand.find(x=>x.currency==='AFN').amount),'5,000');
assert.equal(result.conversions.find(x=>x.from==='PKR').source,decimalUnits('60000'));
assert.equal(result.originals.find(x=>x.cancelled).amount,decimalUnits('140'));
assert.equal(money(decimalUnits('0.1')+decimalUnits('0.2')+decimalUnits('0.2')),'1');
assert.equal(money(decimalUnits('9900000000000000.01')+decimalUnits('0.49')),'9,900,000,000,000,001');
assert.equal(money(decimalUnits('-0.50')),'-1');
cache.set(6,row(6,'AFN','2500'));
cache.set(7,row(7,'PKR','60000'));
cache.set(8,row(8,'AFN','500'));
cache.set(9,row(9,'AFN','999',null,'USD',true));
cache.set(10,{...row(10,'AFN','111'),hasConversion:true});
const pending=summarize(new Set([3,5,6,7,8,9,10]),cache);
assert.equal(money(pending.unconverted.find(x=>x.currency==='AFN').amount),'3,000');
assert.equal(money(pending.unconverted.find(x=>x.currency==='PKR').amount),'60,000');
assert.equal(pending.unconverted.length,2);
assert.equal(pending.pending,3);
assert.equal(pending.incomplete,1);
assert.equal(money(pending.grand.find(x=>x.currency==='USD').amount),'1,000');
assert.equal(summarize(new Set([99]),cache).missing,1);
assert.equal(summarize(new Set(),cache).count,0);
console.log('PASS: exact decimal totals, final-only rounding, large values, native plus converted without double counting, canceled exclusions, currency separation and missing metadata.');
})().catch(error=>{console.error(error);process.exitCode=1;});
